    ]
    Y = collect(reshape(yrow, 18, 3)')
    source = SourceCovariance(Matrix{Float64}(I, 18, 18); groups = 1:18,
        mode = :latent, rank = 1, unique = false, name = :ordinary_latent)
    fit = fit_gaussian_sources(Y; sources = [source], g_tol = 1e-7, iterations = 2000)
    @test fit.converged
    @test fit.gradient_norm <= 1e-7
    @test fit.stopping_reason == :converged
    @test isapprox(fit.loglik, -20.9253282433993, atol = 1e-8)
end
