using Test, GLLVM, LinearAlgebra

# Regression for CORE070 COV-ORD-LATENT-BARE: the direct default-mean latent
# source fit must satisfy the same optimizer-health gate as the explicit-design
# route. The frozen 3x18 response (INPUT-GAUSS-LOADINGS) stalls an Armijo-only
# BackTracking line search on objective roundoff at gradient ~1.7e-6; the
# Hager-Zhang line search reaches the requested g_tol.
@testset "default-mean latent source optimizer health" begin
    yrow = [
        0.52719469679615227, 0.0094320371245146251, -0.30127704858834475, -0.55680249530792825, -0.72901450127076184, -0.79895491709792821,
        -0.75892427466313839, -0.61332939156757993, -0.37819824174430888, -0.079415498198925849, 0.81836980306973706, 1.0414709848078965,
        1.1719379013633127, 1.1954079577517649, 1.1092974268256817, 0.92308588173832451, 0.65727262663581199, 0.3411200080598672,
        0.45012700988217275, 0.49131723555474932, 0.16046322686968412, -0.14402111088936975, -0.3886162822232242, -0.54639575683810793,
        -0.59999020655070345, -0.54349962701548471, -0.38314284623659001, -0.13657291800043492, 0.77415123057121993, 1.056986598718789,
        1.2674968696188058, 1.3825077869863733, 1.3893582466233818, 1.2872941080946945, 1.0875512151130617, 0.81211848524175667,
        0.36906623409883188, 0.96592815535293108, 0.64128486434866616, 0.31209668333493468, 0.014602657751925374, -0.21844725315794511,
