# Hand-declared frozen-source controls; no generated expectations from the subject.
cases <- list()
add <- function(id, expr, expected=NULL, error=NULL) {
 cases[[length(cases)+1L]] <<- list(id=id,expr=substitute(expr),expected=expected,error=error)
}
