# Source-policy probes on intentionally minimal objects, never fitted models.
# `ns` is the namespace of the installed frozen R package supplied by the runner.
f<-function(name)get(name,envir=ns,inherits=FALSE)
formal<-function(name,arg)formals(f(name))[[arg]]
probes<-list()
add<-function(id,expr,expected)probes[[length(probes)+1L]]<<-list(id=id,expr=substitute(expr),expected=substitute(expected))
base<-structure(list(opt=list(objective=12,par=c(b_fix=.2,log_sigma_eps=-.1)),tmb_data=list(y=1:4,is_y_observed=c(1L,0L,1L,1L)),X_fix_names='traitA'),class='gllvmTMB_multi')
add('POST-PREDICT-DEFAULT',formal('predict.gllvmTMB_multi','type'),quote(c('link','response')))
add('POST-FITTED-DEFAULT',formal('fitted.gllvmTMB_multi','type'),quote(c('response','link')))
add('POST-SIMULATE-DEFAULT',formal('simulate.gllvmTMB_multi','condition_on_RE'),FALSE)
add('POST-RESIDUAL-TYPES',formal('residuals.gllvmTMB_multi','type'),quote(c('randomized_quantile','simulation_rank')))
add('POST-RESIDUAL-SCALES',formal('residuals.gllvmTMB_multi','scale'),quote(c('normal','uniform')))
add('POST-RESIDUAL-CONDITIONAL',formal('residuals.gllvmTMB_multi','condition_on_RE'),TRUE)
add('POST-CONFINT-METHODS',formal('confint.gllvmTMB_multi','method'),quote(c('profile','wald','bootstrap')))
add('POST-TIDY-EFFECTS',formal('tidy.gllvmTMB_multi','effects'),quote(c('fixed','ran_pars','cutpoint')))
add('POST-NOBS-MASK',f('nobs.gllvmTMB_multi')(base),3L)
add('POST-NOBS-COUNT',f('nobs.gllvmTMB_multi')(modifyList(base,list(missing_data=list(counts=list(likelihood_rows=2L))))),2L)
add('POST-NOBS-FALLBACK',f('nobs.gllvmTMB_multi')(list(tmb_data=list(y=1:4))),4L)
add('POST-COEF-NAMED',f('coef.gllvmTMB_multi')(base),c(traitA=.2))
add('POST-COEF-EMPTY',f('coef.gllvmTMB_multi')(list()),setNames(numeric(0),character(0)))
add('POST-LOGLIK-VALUE',as.numeric(f('logLik.gllvmTMB_multi')(base)),-12)
add('POST-LOGLIK-NOBS',attr(f('logLik.gllvmTMB_multi')(base),'nobs'),3L)
add('POST-LOGLIK-DF',attr(f('logLik.gllvmTMB_multi')(base),'df'),2L)
add('POST-DEVIANCE',f('deviance.gllvmTMB_multi')(base),24)
error_class<-function(expr)tryCatch({force(expr);'NO_ERROR'},error=function(e)class(e)[1L])
add('POST-SE-NEWDATA-REJECT',error_class(f('.gllvmTMB_predict_se_guard')(base,data.frame(x=1))), 'gllvmTMB_predict_se_newdata_unsupported')
mn<-modifyList(base,list(tmb_data=list(family_id_vec=16L)))
add('POST-SE-MULTINOMIAL-REJECT',error_class(f('.gllvmTMB_predict_se_guard')(mn,NULL)),'gllvmTMB_predict_se_multinomial_unsupported')
mi<-modifyList(base,list(tmb_data=list(has_mi=1L)))
add('POST-SE-MISSING-PREDICTOR-REJECT',error_class(f('.gllvmTMB_predict_se_guard')(mi,NULL)),'gllvmTMB_predict_se_mi_unsupported')
add('POST-SE-REML-REJECT',error_class(f('.gllvmTMB_predict_se_guard')(modifyList(base,list(REML=TRUE)),NULL)),'gllvmTMB_predict_se_reml_unsupported')
add('POST-SE-NO-SDREPORT-REJECT',error_class(f('.gllvmTMB_predict_se_guard')(base,NULL)),'gllvmTMB_predict_se_no_sdreport')
add('POST-SE-GUARD-ADMIT',f('.gllvmTMB_predict_se_guard')(modifyList(base,list(sd_report=list())),NULL),TRUE)
add('POST-LOGNORMAL-RESPONSE-MEAN',f('.apply_linkinv_per_row')(0,3L,0L,sigma_eps=.8),exp(.8^2/2))
add('POST-MIXED-LINK-DISPATCH',f('.apply_linkinv_per_row')(c(.2,.2,.2),c(0L,2L,1L),c(0L,0L,2L)),c(.2,exp(.2),-expm1(-exp(.2))))
add('POST-RE-FORM-ZERO',f('.gllvmTMB_re_form_is_zero')(~0),TRUE)
add('POST-RE-FORM-NA',f('.gllvmTMB_re_form_is_zero')(NA),TRUE)
add('POST-RE-FORM-FULL',f('.gllvmTMB_re_form_is_zero')(~.),FALSE)
# The frozen response helper returns the untruncated Poisson rate, not E[Y|Y>0].
add('POST-TRUNCPOIS-RESPONSE-PARAMETER',f('.apply_linkinv_per_row')(log(.5),10L,0L),.5)
